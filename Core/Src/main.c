/* ====================================== */
/* 4. 系统时钟配置：HIRC + 总线/等待周期    */
/*    这是系统底层，一般不用改               */
/* ====================================== */
static void SystemClock_Config(void)
{
    /* 4.1 允许访问扩展 SFR（XFR）
     *     STC32G 的 PnPU/PnPD/PnSR 等寄存器在 0x7EFE00 区域，
     *     必须先置 P_SW2.7（EAXFR）=1，否则读写无效。 */
    EAXFR_ENABLE();

    /* 4.2 片内 XRAM 总线时钟拉到最快
     *     CKCON=0：CPU 访问片内 xdata 不额外插等待。 */
    CKCON = 0x00;

    /* 4.3 Flash 读取等待周期
     *     i-Cache 出厂常开且不可关闭，WTST 必须 >=1（写 0 无效）。
     *     24MHz 用 WTST=1；48MHz 仍可用 1；>64MHz 按规格书加到 2~4。 */
    WTST = 1;

    /* 4.4 主频说明
     *     STC32G 复位后先跑 ISP 监控程序（固定 24MHz HIRC），
     *     跳转到用户程序后使用“上次 ISP 下载时修调的 HIRC 频率”。
     *     用户程序不需要（也不能）像 STM32 那样在这里配 PLL 倍频；
     *     要换频率请在 AiCube-ISP 里选，并同步改 MAIN_Fosc。 */
}

/* ====================================== */
/* 5. 板载 LED GPIO 初始化                  */
/*    P0.0 = LED（低电平亮）                 */
/*    P4.1 = LED 电源使能（低电平有效）       */
/*    这是板级驱动，一般不用改               */
/* ====================================== */
static void LED_Init(void)
{
    /* 5.1 上电默认所有 I/O 都是高阻输入，必须先配模式 */
    /*     PnM1:PnM0 = 00 准双向 / 01 强推挽 / 10 高阻 / 11 开漏 */

    /* 5.2 P0 整口配成强推挽输出（P0.0 作 LED） */
    P0M1 = 0x00;
    P0M0 = 0xFF;

    /* 5.3 P4.1 配成强推挽输出（LED 电源使能） */
    P4M1 = 0x00;
    P4M0 = 0x02;

    /* 5.4 打开 LED 电源，先熄灭 LED（低电平亮，所以先输出高） */
    LED_PWR_ON();
    LED_OFF();
}

